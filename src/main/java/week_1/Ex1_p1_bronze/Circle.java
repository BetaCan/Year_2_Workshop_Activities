package week_1.Ex1_p1_bronze;

public class Circle
{	  	  	  	       		   	      	
  public double radius, x, y;	  	  	  	       		   	      	
	  	  	  	       		   	      	
	  	  	  	       		   	      	
	  	  	  	       		   	      	
  public double calculateCircumference()	  	  	  	       		   	      	
  {	  	  	  	       		   	      	
    return 2 * Math.PI * radius;	  	  	  	       		   	      	
  }	  	  	  	       		   	      	
	  	  	  	       		   	      	
  public double calculateSurfaceArea()	  	  	  	       		   	      	
  {	  	  	  	       		   	      	
    return Math.PI * radius * radius;	  	  	  	       		   	      	
  }	  	  	  	       		   	      	
	  	  	  	       		   	      	
	  	  	  	       		   	      	
}