package week_1_task_2.task_2;

public class Maths
{	  	  	  	       		   	      	
	  	  	  	       		   	      	
  public static int abs(int x)	  	  	  	       		   	      	
  {	  	  	  	       		   	      	
    if (x > 0) return x;	  	  	  	       		   	      	
    return -x;	  	  	  	       		   	      	
  }	  	  	  	       		   	      	
  public static int max(int x, int y)	  	  	  	       		   	      	
  {	  	  	  	       		   	      	
    return Math.max(x, y);	  	  	  	       		   	      	
  }


}